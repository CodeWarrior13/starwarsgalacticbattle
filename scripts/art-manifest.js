// Scans art/ for images named after unit ids (luke.png, slave_one.jpg, ...)
// and writes js/art-images.js so the game shows them instead of the drawn art.
// Run with: npm run art
const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '..');
const artDir = path.join(rootDir, 'art');
global.window = global;
require(path.join(rootDir, 'js/data.js'));
const ids = new Set(global.GameData.UNITS.map((u) => u.id));

const map = {};
const unknown = [];
for (const file of fs.existsSync(artDir) ? fs.readdirSync(artDir).sort() : []) {
  const m = file.match(/^(.+)\.(png|jpe?g|webp|gif|svg)$/i);
  if (!m) continue;
  if (ids.has(m[1])) map[m[1]] = `art/${file}`;
  else unknown.push(file);
}
const out = `// Generated by scripts/art-manifest.js. Unit id -> image path in art/.\nwindow.ART_IMAGES = ${JSON.stringify(map, null, 2)};\n`;
fs.writeFileSync(path.join(rootDir, 'js/art-images.js'), out);
console.log(`Mapped ${Object.keys(map).length} image(s).`);
if (unknown.length) console.log(`Skipped (name does not match a unit id): ${unknown.join(', ')}`);
